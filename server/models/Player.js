const mongoose = require('mongoose');

const playerSchema = new mongoose.Schema({
  player_id: { type: Number, unique: true, required: true },
  player: { type: String, required: true },
  slug: String,
  team: String,
  team_id: Number,
  league: String,
  position: String,
  detailed_position: String,
  role: String,
  season: String,
  appearances: { type: Number, default: 0 },
  minutes: { type: Number, default: 0 },
  goals: { type: Number, default: 0 },
  assists: { type: Number, default: 0 },
  xg: { type: Number, default: 0 },
  xa: { type: Number, default: 0 },
  shots: { type: Number, default: 0 },
  shots_on_target: { type: Number, default: 0 },
  passes: { type: Number, default: 0 },
  total_passes: { type: Number, default: 0 },
  key_passes: { type: Number, default: 0 },
  long_balls: { type: Number, default: 0 },
  total_long_balls: { type: Number, default: 0 },
  crosses: { type: Number, default: 0 },
  total_crosses: { type: Number, default: 0 },
  final_third_passes: { type: Number, default: 0 },
  dribbles: { type: Number, default: 0 },
  total_dribbles: { type: Number, default: 0 },
  dispossessed: { type: Number, default: 0 },
  touches: { type: Number, default: 0 },
  tackles_won: { type: Number, default: 0 },
  total_tackles: { type: Number, default: 0 },
  interceptions: { type: Number, default: 0 },
  recoveries: { type: Number, default: 0 },
  clearances: { type: Number, default: 0 },
  blocked_shots: { type: Number, default: 0 },
  aerials_won: { type: Number, default: 0 },
  total_aerials: { type: Number, default: 0 },
  yellows: { type: Number, default: 0 },
  reds: { type: Number, default: 0 },
  big_chances_created: { type: Number, default: 0 },
  big_chances_missed: { type: Number, default: 0 },
  errors_to_goal: { type: Number, default: 0 },
  penalties_won: { type: Number, default: 0 },
  penalties_conceded: { type: Number, default: 0 },
  // Per-90 stats
  goals_p90: { type: Number, default: 0 },
  assists_p90: { type: Number, default: 0 },
  xg_p90: { type: Number, default: 0 },
  xa_p90: { type: Number, default: 0 },
  shots_p90: { type: Number, default: 0 },
  shots_on_target_p90: { type: Number, default: 0 },
  big_chances_created_p90: { type: Number, default: 0 },
  big_chances_missed_p90: { type: Number, default: 0 },
  passes_p90: { type: Number, default: 0 },
  total_passes_p90: { type: Number, default: 0 },
  key_passes_p90: { type: Number, default: 0 },
  long_balls_p90: { type: Number, default: 0 },
  total_long_balls_p90: { type: Number, default: 0 },
  crosses_p90: { type: Number, default: 0 },
  total_crosses_p90: { type: Number, default: 0 },
  final_third_passes_p90: { type: Number, default: 0 },
  dribbles_p90: { type: Number, default: 0 },
  total_dribbles_p90: { type: Number, default: 0 },
  dispossessed_p90: { type: Number, default: 0 },
  touches_p90: { type: Number, default: 0 },
  tackles_won_p90: { type: Number, default: 0 },
  total_tackles_p90: { type: Number, default: 0 },
  interceptions_p90: { type: Number, default: 0 },
  recoveries_p90: { type: Number, default: 0 },
  clearances_p90: { type: Number, default: 0 },
  blocked_shots_p90: { type: Number, default: 0 },
  errors_to_goal_p90: { type: Number, default: 0 },
  aerials_won_p90: { type: Number, default: 0 },
  total_aerials_p90: { type: Number, default: 0 },
  yellows_p90: { type: Number, default: 0 },
  reds_p90: { type: Number, default: 0 },
  penalties_won_p90: { type: Number, default: 0 },
  penalties_conceded_p90: { type: Number, default: 0 },
});

playerSchema.index({ team_id: 1 });
playerSchema.index({ league: 1 });
playerSchema.index({ position: 1 });
playerSchema.index({ player: 'text' });

module.exports = mongoose.model('Player', playerSchema);
